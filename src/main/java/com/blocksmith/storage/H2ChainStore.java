package com.blocksmith.storage;

import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import java.util.OptionalInt;

import com.blocksmith.core.Block;
import com.blocksmith.core.Transaction;
import com.blocksmith.util.JsonUtil;

/**
 * {@link ChainStore} backed by an embedded H2 database (JDBC).
 *
 * THEORY: A JSON blob plus a few indexed columns
 *
 * Each block is stored as the same Gson JSON the P2P layer already exchanges
 * between peers, next to the handful of columns we need to look rows up:
 *
 *   blocks                                   pending_tx
 *   +-----+----------+---------------+-----+ +-----+-------+------+
 *   | idx | hash     | previous_hash | json| | seq | tx_id | json |
 *   +-----+----------+---------------+-----+ +-----+-------+------+
 *   | 0   | 0000c6.. | 0             | {..}| | 1   | ba09..| {..} |
 *   | 1   | 0000ce.. | 0000c6..      | {..}| | 2   | d348..| {..} |
 *
 * Why not one table per field (a fully normalised schema)? A block is always
 * read and written as a whole, and its exact content matters: the hash is
 * recomputed from it on restore. Storing the serialized block keeps the
 * mapping trivial and lossless; the extra columns exist only for lookups.
 *
 * Lookups (Sprint 16c) get their own table, filled whenever a block is saved:
 *
 *   tx_index: tx_id (PK) | block_idx | pos | sender | recipient | amount
 *             indexes on sender, recipient and block_idx
 *
 * THEORY: Why an index makes "history of an address" fast
 *
 * Without one, finding every transaction of an address means reading every
 * transaction of every block (a full scan, O(all transactions)). A B-tree
 * index on `sender` keeps the rows sorted by sender, so the database jumps
 * straight to the matching ones (O(log n + matches)). Bitcoin Core's
 * optional `-txindex` and block explorers do the same thing.
 *
 * A database created before 16c has no index rows yet; they fill in on the
 * next startup, because restore re-saves every replayed block.
 *
 * WHY EMBEDDED H2: it is plain Java (no native driver), runs inside the node
 * process, and has an in-memory mode that makes tests fast and isolated.
 *
 * Thread safety: the node touches the chain from network handlers and API
 * threads, so every method is synchronized on the single connection.
 */
public class H2ChainStore implements ChainStore {

    private static final String CREATE_BLOCKS =
            "CREATE TABLE IF NOT EXISTS blocks ("
            + " idx INT PRIMARY KEY,"
            + " hash VARCHAR(128) NOT NULL UNIQUE,"
            + " previous_hash VARCHAR(128) NOT NULL,"
            + " json CLOB NOT NULL)";

    private static final String CREATE_PENDING =
            "CREATE TABLE IF NOT EXISTS pending_tx ("
            + " seq BIGINT GENERATED BY DEFAULT AS IDENTITY,"
            + " tx_id VARCHAR(128) PRIMARY KEY,"
            + " json CLOB NOT NULL)";

    private static final String CREATE_TX_INDEX =
            "CREATE TABLE IF NOT EXISTS tx_index ("
            + " tx_id VARCHAR(128) PRIMARY KEY,"
            + " block_idx INT NOT NULL,"
            + " pos INT NOT NULL,"
            + " sender VARCHAR(256) NOT NULL,"
            + " recipient VARCHAR(256) NOT NULL,"
            + " amount DOUBLE NOT NULL)";

    private static final String[] CREATE_TX_INDEXES = {
            "CREATE INDEX IF NOT EXISTS idx_tx_sender ON tx_index (sender)",
            "CREATE INDEX IF NOT EXISTS idx_tx_recipient ON tx_index (recipient)",
            "CREATE INDEX IF NOT EXISTS idx_tx_block ON tx_index (block_idx)"
    };

    private static final String MERGE_TX_INDEX =
            "MERGE INTO tx_index (tx_id, block_idx, pos, sender, recipient, amount)"
            + " KEY (tx_id) VALUES (?, ?, ?, ?, ?, ?)";

    // Sent OR received, newest first. Two indexed halves joined with UNION ALL
    // (each half can use its own index); the second half skips self-transfers
    // so a tx from A to A is listed once.
    private static final String SELECT_BY_ADDRESS =
            "SELECT tx_id, block_idx, pos FROM tx_index WHERE sender = ?"
            + " UNION ALL"
            + " SELECT tx_id, block_idx, pos FROM tx_index WHERE recipient = ? AND sender <> ?"
            + " ORDER BY block_idx DESC, pos DESC";

    // MERGE ... KEY(..) = insert, or update the row with that key: one block
    // per height and one row per pending tx, so repeated saves are no-ops.
    private static final String MERGE_BLOCK =
            "MERGE INTO blocks (idx, hash, previous_hash, json) KEY (idx) VALUES (?, ?, ?, ?)";
    private static final String MERGE_PENDING =
            "MERGE INTO pending_tx (tx_id, json) KEY (tx_id) VALUES (?, ?)";

    private final Connection connection;

    /**
     * Opens (or creates) a database at the given JDBC URL and makes sure the
     * schema exists.
     *
     * @param jdbcUrl for example {@code jdbc:h2:mem:test} or {@code jdbc:h2:file:/data/chain}
     * @throws StorageException if the database cannot be opened
     */
    public H2ChainStore(String jdbcUrl) {
        try {
            this.connection = DriverManager.getConnection(jdbcUrl);
            try (Statement st = connection.createStatement()) {
                st.execute(CREATE_BLOCKS);
                st.execute(CREATE_PENDING);
                st.execute(CREATE_TX_INDEX);
                for (String sql : CREATE_TX_INDEXES) st.execute(sql);
            }
        } catch (SQLException e) {
            throw new StorageException("Cannot open chain database at " + jdbcUrl, e);
        }
    }

    /**
     * Opens a file database inside {@code directory} (created if missing).
     * The data lives in {@code <directory>/chain.mv.db}.
     */
    public static H2ChainStore openFile(Path directory) {
        try {
            Files.createDirectories(directory);
        } catch (Exception e) {
            throw new StorageException("Cannot create data directory " + directory, e);
        }
        // H2 wants an absolute path; forward slashes work on every OS.
        String path = directory.toAbsolutePath().resolve("chain").toString().replace('\\', '/');
        return new H2ChainStore("jdbc:h2:file:" + path);
    }

    /**
     * Opens a private in-memory database. It disappears when the store is
     * closed, which is exactly what a test wants.
     */
    public static H2ChainStore openInMemory(String name) {
        return new H2ChainStore("jdbc:h2:mem:" + name);
    }

    // ===== BLOCKS =====

    /**
     * Saves the block and its index rows in ONE database transaction, so a
     * crash can never leave a block without its index (or the reverse).
     * Re-saving a height first drops that height's old index rows.
     */
    @Override
    public synchronized void saveBlock(Block block) {
        try {
            connection.setAutoCommit(false);
            try (PreparedStatement ps = connection.prepareStatement(MERGE_BLOCK)) {
                ps.setInt(1, block.getIndex());
                ps.setString(2, block.getHash());
                ps.setString(3, block.getPreviousHash());
                ps.setString(4, JsonUtil.GSON.toJson(block));
                ps.executeUpdate();
            }
            try (PreparedStatement del = connection.prepareStatement(
                    "DELETE FROM tx_index WHERE block_idx = ?")) {
                del.setInt(1, block.getIndex());
                del.executeUpdate();
            }
            try (PreparedStatement ix = connection.prepareStatement(MERGE_TX_INDEX)) {
                List<Transaction> txs = block.getTransactions();
                for (int pos = 0; pos < txs.size(); pos++) {
                    Transaction tx = txs.get(pos);
                    ix.setString(1, tx.getTransactionId());
                    ix.setInt(2, block.getIndex());
                    ix.setInt(3, pos);
                    ix.setString(4, tx.getSender());
                    ix.setString(5, tx.getRecipient());
                    ix.setDouble(6, tx.getAmount());
                    ix.addBatch();
                }
                ix.executeBatch();
            }
            connection.commit();
        } catch (SQLException e) {
            rollbackQuietly();
            throw new StorageException("Cannot save block #" + block.getIndex(), e);
        } finally {
            try {
                connection.setAutoCommit(true);
            } catch (SQLException ignored) {
                // The connection is unusable anyway; the next call will report it.
            }
        }
    }

    private void rollbackQuietly() {
        try {
            connection.rollback();
        } catch (SQLException ignored) {
            // Nothing more we can do; the original error is what matters.
        }
    }

    @Override
    public synchronized List<Block> loadBlocks() {
        List<Block> blocks = new ArrayList<>();
        try (Statement st = connection.createStatement();
             ResultSet rs = st.executeQuery("SELECT json FROM blocks ORDER BY idx")) {
            while (rs.next()) {
                blocks.add(JsonUtil.GSON.fromJson(rs.getString(1), Block.class));
            }
        } catch (SQLException e) {
            throw new StorageException("Cannot load blocks", e);
        }
        return blocks;
    }

    // ===== PENDING TRANSACTIONS =====

    @Override
    public synchronized void savePending(Transaction transaction) {
        try (PreparedStatement ps = connection.prepareStatement(MERGE_PENDING)) {
            ps.setString(1, transaction.getTransactionId());
            ps.setString(2, JsonUtil.GSON.toJson(transaction));
            ps.executeUpdate();
        } catch (SQLException e) {
            throw new StorageException("Cannot save pending transaction "
                    + transaction.getTransactionId(), e);
        }
    }

    @Override
    public synchronized void removePending(String transactionId) {
        try (PreparedStatement ps = connection.prepareStatement(
                "DELETE FROM pending_tx WHERE tx_id = ?")) {
            ps.setString(1, transactionId);
            ps.executeUpdate();
        } catch (SQLException e) {
            throw new StorageException("Cannot remove pending transaction " + transactionId, e);
        }
    }

    @Override
    public synchronized List<Transaction> loadPending() {
        List<Transaction> pending = new ArrayList<>();
        // Order matters: replaying in arrival order keeps the balance checks
        // identical (a spend that relied on an earlier pending tx stays valid).
        try (Statement st = connection.createStatement();
             ResultSet rs = st.executeQuery("SELECT json FROM pending_tx ORDER BY seq")) {
            while (rs.next()) {
                pending.add(JsonUtil.GSON.fromJson(rs.getString(1), Transaction.class));
            }
        } catch (SQLException e) {
            throw new StorageException("Cannot load pending transactions", e);
        }
        return pending;
    }

    // ===== INDEXED LOOKUPS =====

    @Override
    public boolean isIndexed() {
        return true;
    }

    @Override
    public synchronized OptionalInt findBlockIndexByHash(String hash) {
        return queryInt("SELECT idx FROM blocks WHERE hash = ?", hash);
    }

    @Override
    public synchronized OptionalInt findTransactionBlockIndex(String transactionId) {
        return queryInt("SELECT block_idx FROM tx_index WHERE tx_id = ?", transactionId);
    }

    @Override
    public synchronized List<TxRef> findTransactionsByAddress(String address) {
        List<TxRef> refs = new ArrayList<>();
        try (PreparedStatement ps = connection.prepareStatement(SELECT_BY_ADDRESS)) {
            ps.setString(1, address);
            ps.setString(2, address);
            ps.setString(3, address);
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) refs.add(new TxRef(rs.getString(1), rs.getInt(2)));
            }
        } catch (SQLException e) {
            throw new StorageException("Cannot query transactions of " + address, e);
        }
        return refs;
    }

    /** Runs a single-parameter query that returns at most one int. */
    private OptionalInt queryInt(String sql, String param) {
        try (PreparedStatement ps = connection.prepareStatement(sql)) {
            ps.setString(1, param);
            try (ResultSet rs = ps.executeQuery()) {
                return rs.next() ? OptionalInt.of(rs.getInt(1)) : OptionalInt.empty();
            }
        } catch (SQLException e) {
            throw new StorageException("Lookup failed: " + sql, e);
        }
    }

    // ===== BACKUP & RESTORE (Sprint 16d) =====

    /** Name of the database file inside a data directory and inside a backup zip. */
    static final String DB_FILE = "chain.mv.db";

    /**
     * THEORY: Online backup
     *
     * H2's {@code BACKUP TO} copies the database file into a zip while the
     * database stays open. It is a consistent snapshot: blocks saved after
     * the command started are simply not in it. Nothing has to stop, which
     * matters for a node that peers expect to stay online.
     *
     * Only file databases can be backed up (an in-memory one has no file).
     *
     * @param zipFile where to write the backup; must not exist yet
     */
    @Override
    public synchronized void backup(Path zipFile) {
        try {
            if (Files.exists(zipFile)) {
                throw new StorageException("Backup target already exists: " + zipFile, null);
            }
            Path parent = zipFile.toAbsolutePath().getParent();
            if (parent != null) Files.createDirectories(parent);
            String target = zipFile.toAbsolutePath().toString().replace('\\', '/').replace("'", "''");
            try (Statement st = connection.createStatement()) {
                st.execute("BACKUP TO '" + target + "'");
            }
        } catch (SQLException | java.io.IOException e) {
            throw new StorageException("Backup to " + zipFile + " failed", e);
        }
    }

    /**
     * Installs a backup as the database of {@code dataDirectory}, before the
     * node opens it.
     *
     * THEORY: Restore carefully, then validate anyway
     *
     *   1. Unpack into a temporary folder, never straight into the data dir
     *   2. Accept exactly one entry, chain.mv.db (rejects foreign zips and
     *      "zip slip" names like ../../evil)
     *   3. Open it once: a damaged database file fails HERE, while the
     *      current data is still untouched
     *   4. Only then move the current database aside (renamed, not deleted)
     *      and put the backup in its place
     *
     * After this the node starts normally, and restoreFromStore() replays
     * every block through validation. A backup is trusted no more than the
     * live database is.
     *
     * @return the path the previous database was moved to, or null if there was none
     * @throws StorageException if the backup is missing, not a BlockSmith backup, or damaged
     */
    public static Path restoreBackup(Path zipFile, Path dataDirectory) {
        if (!Files.isRegularFile(zipFile)) {
            throw new StorageException("Backup file not found: " + zipFile, null);
        }
        Path staging = null;
        try {
            Files.createDirectories(dataDirectory);
            staging = Files.createTempDirectory(dataDirectory.toAbsolutePath(), "restore-");
            Path unpacked = unpackBackup(zipFile, staging);

            // Step 3: make sure H2 can actually read it (IFEXISTS: never create).
            String url = "jdbc:h2:file:" + staging.resolve("chain").toString().replace('\\', '/')
                    + ";IFEXISTS=TRUE";
            try (H2ChainStore probe = new H2ChainStore(url)) {
                probe.loadBlocks();
            } catch (RuntimeException e) {
                throw new StorageException("Backup " + zipFile + " is damaged: the database cannot be read", e);
            }

            // Step 4: keep the old database, then swap in the backup.
            Path live = dataDirectory.resolve(DB_FILE);
            Path previous = null;
            if (Files.exists(live)) {
                previous = dataDirectory.resolve(DB_FILE + ".before-restore-" + System.currentTimeMillis());
                Files.move(live, previous);
            }
            Files.move(unpacked, live);
            return previous;
        } catch (java.io.IOException e) {
            throw new StorageException("Restore from " + zipFile + " failed", e);
        } finally {
            deleteQuietly(staging);
        }
    }

    /** Unpacks the single expected entry of a backup zip into {@code staging}. */
    private static Path unpackBackup(Path zipFile, Path staging) throws java.io.IOException {
        Path out = null;
        try (java.util.zip.ZipInputStream zip =
                     new java.util.zip.ZipInputStream(Files.newInputStream(zipFile))) {
            java.util.zip.ZipEntry entry;
            while ((entry = zip.getNextEntry()) != null) {
                if (!DB_FILE.equals(entry.getName()) || out != null) {
                    throw new StorageException("Not a BlockSmith backup: unexpected entry '"
                            + entry.getName() + "' in " + zipFile, null);
                }
                out = staging.resolve(DB_FILE);
                Files.copy(zip, out);
            }
        } catch (java.util.zip.ZipException e) {
            throw new StorageException("Not a BlockSmith backup: " + zipFile + " is not a valid zip", e);
        }
        if (out == null) {
            throw new StorageException("Not a BlockSmith backup: no " + DB_FILE + " in " + zipFile, null);
        }
        return out;
    }

    private static void deleteQuietly(Path dir) {
        if (dir == null || !Files.exists(dir)) return;
        try (java.util.stream.Stream<Path> paths = Files.walk(dir)) {
            paths.sorted(java.util.Comparator.reverseOrder()).forEach(p -> {
                try {
                    Files.deleteIfExists(p);
                } catch (java.io.IOException ignored) {
                    // Leftover temp files are harmless.
                }
            });
        } catch (java.io.IOException ignored) {
            // Same: best effort cleanup.
        }
    }

    // ===== LIFECYCLE =====

    @Override
    public synchronized void close() {
        try {
            if (!connection.isClosed()) connection.close();
        } catch (SQLException e) {
            throw new StorageException("Cannot close chain database", e);
        }
    }
}
